const VALIDATION_PATTERNS: Array<[RegExp, string]> = [
  [/^Höchstens ([\d.]+) Zeichen\.$/, "At most $1 characters."],
  [/^Mindestens ([\d.]+) Zeichen\.$/, "At least $1 characters."],
  [/^Höchstens ([\d.]+) Adressen auf einmal\.$/, "At most $1 addresses at once."],
  [/^Höchstens ([\d.]+)\.$/, "At most $1."],
  [/^Mindestens ([\d.]+)\.$/, "At least $1."],
  [/^Keine gültige Firmen-E-Mail: (.*)$/, "Not a valid company email: $1"],
];

function translateValidation(message: string): string {
  const exact = VALIDATION[message];
  if (exact) return exact;
  for (const [re, replacement] of VALIDATION_PATTERNS) if (re.test(message)) return message.replace(re, replacement);
  return message;
}

